-- 1. 起名历史表
create table if not exists public.name_history (
  id              bigint generated by default as identity primary key,
  user_requirement text        not null,              -- 用户输入的起名需求
  name_result      text        not null,              -- 模型返回的完整命名方案
  model_name       text        not null,              -- 使用的模型（deepseek / doubao / qwen / kimi）
  created_at       timestamp with time zone default now()
);

comment on table  public.name_history               is 'AI 起名平台：起名历史记录';
comment on column public.name_history.user_requirement is '用户起名需求';
comment on column public.name_history.name_result      is '生成的起名方案（含寓意）';

-- 2. 常用索引：按时间倒序查最近记录
create index if not exists idx_name_history_created_at
  on public.name_history (created_at desc);

-- ============================================================
-- 3. 权限（RLS）
--    调试期：可以直接用下面这套「匿名可读写」，页面立刻能存能查。
--    正式上线：见第 4 段的收紧方案。
-- ============================================================
alter table public.name_history enable row level security;

drop policy if exists "anon can insert name_history" on public.name_history;
create policy "anon can insert name_history"
  on public.name_history for insert
  to anon, authenticated
  with check (true);

drop policy if exists "anon can read name_history" on public.name_history;
create policy "anon can read name_history"
  on public.name_history for select
  to anon, authenticated
  using (true);

